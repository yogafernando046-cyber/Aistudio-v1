-- KASIR IDRIS: hapus/pulihkan transaksi secara atomik.
-- Jalankan SATU KALI di SQL Editor pada proyek Supabase yang benar.
-- Tidak menonaktifkan RLS dan tidak menghapus data saat pemasangan.

CREATE TABLE IF NOT EXISTS public.deleted_sales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id uuid NOT NULL,
  original_sale_id text NOT NULL,
  client_tx_id text,
  transaction_data jsonb NOT NULL,
  deleted_at text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (store_id, original_sale_id)
);
ALTER TABLE public.deleted_sales ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "kasir deleted sales read members" ON public.deleted_sales;
CREATE POLICY "kasir deleted sales read members" ON public.deleted_sales
  FOR SELECT TO authenticated USING (public.is_store_member(store_id));

CREATE OR REPLACE FUNCTION public.kasir_delete_sale_atomic(
  p_store_id uuid, p_sale_id text, p_transaction_data jsonb
) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_sale_id text; v_deleted integer;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.store_members sm
    WHERE sm.store_id=p_store_id AND sm.user_id=auth.uid()
      AND sm.active=true
  ) THEN RAISE EXCEPTION 'Tidak berizin menghapus transaksi toko ini'; END IF;

  SELECT s.id::text INTO v_sale_id FROM public.sales s
   WHERE s.store_id=p_store_id AND s.id::text=p_sale_id FOR UPDATE;
  IF v_sale_id IS NULL THEN RAISE EXCEPTION 'Transaksi tidak ditemukan di Supabase'; END IF;

  INSERT INTO public.deleted_sales(store_id,original_sale_id,client_tx_id,transaction_data,deleted_at)
  SELECT p_store_id, v_sale_id, s.client_tx_id::text,
         COALESCE(p_transaction_data, '{}'::jsonb) || jsonb_build_object('serverSaleId',v_sale_id,'serverClientTxId',s.client_tx_id),
         now()::text
  FROM public.sales s WHERE s.store_id=p_store_id AND s.id::text=v_sale_id
  ON CONFLICT (store_id,original_sale_id) DO UPDATE
    SET transaction_data=EXCLUDED.transaction_data, client_tx_id=EXCLUDED.client_tx_id, deleted_at=EXCLUDED.deleted_at;

  DELETE FROM public.sale_items si WHERE si.store_id=p_store_id AND si.sale_id::text=v_sale_id;
  DELETE FROM public.sales s WHERE s.store_id=p_store_id AND s.id::text=v_sale_id;
  GET DIAGNOSTICS v_deleted = ROW_COUNT;
  IF v_deleted <> 1 THEN RAISE EXCEPTION 'Transaksi utama tidak terhapus; perubahan dibatalkan'; END IF;
  RETURN true;
END;
$$;

CREATE OR REPLACE FUNCTION public.kasir_clear_sales_atomic(p_store_id uuid)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE s record; v_notes jsonb; v_tx jsonb; v_count integer;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.store_members sm
    WHERE sm.store_id=p_store_id AND sm.user_id=auth.uid()
      AND sm.active=true
  ) THEN RAISE EXCEPTION 'Tidak berizin menghapus transaksi toko ini'; END IF;

  -- Arsipkan lima transaksi terbaru sebelum perubahan aktif.
  FOR s IN SELECT * FROM public.sales WHERE store_id=p_store_id ORDER BY created_at DESC LIMIT 5 LOOP
    v_notes := '{}'::jsonb;
    BEGIN
      IF s.notes IS NOT NULL THEN v_notes := s.notes::jsonb; END IF;
    EXCEPTION WHEN others THEN v_notes := '{}'::jsonb;
    END;
    v_tx := COALESCE(v_notes->'app_tx', jsonb_build_object(
      'customer',s.customer,'status',s.status,'total',s.total,'subtotal',s.subtotal,
      'discount',s.discount,'profit',s.profit,'date',s.created_at::text,'items',jsonb_build_array()
    ));
    v_tx := v_tx || jsonb_build_object('serverSaleId',s.id::text,'serverClientTxId',s.client_tx_id,'deletedAt',now()::text);
    INSERT INTO public.deleted_sales(store_id,original_sale_id,client_tx_id,transaction_data,deleted_at)
    VALUES(p_store_id,s.id::text,s.client_tx_id::text,v_tx,now()::text)
    ON CONFLICT (store_id,original_sale_id) DO UPDATE
      SET transaction_data=EXCLUDED.transaction_data,client_tx_id=EXCLUDED.client_tx_id,deleted_at=EXCLUDED.deleted_at;
  END LOOP;

  DELETE FROM public.sale_items WHERE store_id=p_store_id;
  DELETE FROM public.sales WHERE store_id=p_store_id;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.kasir_restore_deleted_sale(
  p_store_id uuid, p_original_sale_id text
) RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE a public.deleted_sales%ROWTYPE; tx jsonb; item jsonb; v_new_id text; v_client_id text; v_sale_id_type text;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.store_members sm
    WHERE sm.store_id=p_store_id AND sm.user_id=auth.uid()
      AND sm.active=true
  ) THEN RAISE EXCEPTION 'Tidak berizin memulihkan transaksi toko ini'; END IF;

  SELECT * INTO a FROM public.deleted_sales
   WHERE store_id=p_store_id AND original_sale_id=p_original_sale_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Arsip transaksi tidak ditemukan'; END IF;
  tx := a.transaction_data;
  v_client_id := gen_random_uuid()::text;

  INSERT INTO public.sales(store_id,client_tx_id,cashier_id,cashier_name,customer,status,subtotal,discount,total,cash_paid,qris_paid,profit,notes,created_at)
  VALUES(p_store_id,v_client_id,auth.uid(),'Pemulihan dari arsip',COALESCE(tx->>'customer','Umum'),COALESCE(tx->>'status','Lunas'),
    COALESCE(NULLIF(tx->>'subtotal','')::numeric,0),COALESCE(NULLIF(tx->>'discount','')::numeric,0),COALESCE(NULLIF(tx->>'total','')::numeric,0),
    COALESCE(NULLIF(tx->>'cashPaid','')::numeric,0),COALESCE(NULLIF(tx->>'qrisPaid','')::numeric,0),COALESCE(NULLIF(tx->>'profit','')::numeric,0),
    jsonb_build_object('app_tx',tx,'restored_from_deleted_sale',p_original_sale_id)::text,now())
  RETURNING id::text INTO v_new_id;

  IF jsonb_typeof(tx->'items')='array' THEN
    SELECT udt_name INTO v_sale_id_type FROM information_schema.columns
      WHERE table_schema='public' AND table_name='sale_items' AND column_name='sale_id';
    IF v_sale_id_type IS NULL THEN RAISE EXCEPTION 'Kolom sale_items.sale_id tidak ditemukan'; END IF;
    FOR item IN SELECT value FROM jsonb_array_elements(tx->'items') LOOP
      EXECUTE format('INSERT INTO public.sale_items(store_id,sale_id,product_id,barcode,product_name,qty,price,cost,line_total) VALUES ($1,$2::%s,NULL,$3,$4,$5,$6,$7,$8)', v_sale_id_type)
      USING p_store_id,v_new_id,COALESCE(item->>'barcode',''),COALESCE(item->>'name',item->>'product_name','Barang'),
        GREATEST(COALESCE(NULLIF(item->>'qty','')::integer,1),1),COALESCE(NULLIF(item->>'price','')::numeric,0),COALESCE(NULLIF(item->>'cost','')::numeric,0),
        COALESCE(NULLIF(item->>'price','')::numeric,0)*GREATEST(COALESCE(NULLIF(item->>'qty','')::integer,1),1);
    END LOOP;
  END IF;
  DELETE FROM public.deleted_sales WHERE id=a.id;
  RETURN v_new_id;
END;
$$;

REVOKE ALL ON FUNCTION public.kasir_delete_sale_atomic(uuid,text,jsonb) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.kasir_clear_sales_atomic(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.kasir_restore_deleted_sale(uuid,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.kasir_delete_sale_atomic(uuid,text,jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION public.kasir_clear_sales_atomic(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.kasir_restore_deleted_sale(uuid,text) TO authenticated;

-- Periksa setelah SQL dijalankan; hasil harus menampilkan ketiga fungsi di bawah.
SELECT routine_name FROM information_schema.routines
WHERE routine_schema='public' AND routine_name IN
('kasir_delete_sale_atomic','kasir_clear_sales_atomic','kasir_restore_deleted_sale');


-- REALTIME: tambahkan tabel yang dipantau aplikasi ke publication Supabase.
-- Aman dijalankan berulang; tidak menonaktifkan RLS dan tidak menghapus data.
DO $$
DECLARE t text;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    FOREACH t IN ARRAY ARRAY['sales','sale_items','deleted_sales','expenses','products'] LOOP
      IF to_regclass('public.' || t) IS NOT NULL
         AND NOT EXISTS (
           SELECT 1 FROM pg_publication_tables
           WHERE pubname='supabase_realtime' AND schemaname='public' AND tablename=t
         ) THEN
        EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', t);
      END IF;
    END LOOP;
  ELSE
    RAISE NOTICE 'Publication supabase_realtime belum ada; aktifkan Realtime melalui Dashboard Supabase.';
  END IF;
END $$;

-- Pemeriksaan: daftar tabel yang sudah dipublikasikan untuk Realtime.
SELECT schemaname, tablename FROM pg_publication_tables
WHERE pubname='supabase_realtime' AND schemaname='public'
  AND tablename IN ('sales','sale_items','deleted_sales','expenses','products')
ORDER BY tablename;
