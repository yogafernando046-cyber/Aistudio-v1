-- KASIR IDRIS - SQL tambahan aman (idempotent)
-- Jalankan di Supabase SQL Editor pada proyek yang benar.
-- Tidak menonaktifkan RLS, tidak menghapus data lama, dan tidak mengubah transaksi lama.

-- 1) Batas stok minimum per produk.
ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS min_stock integer NOT NULL DEFAULT 0;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.products'::regclass AND conname='products_min_stock_nonnegative_chk') THEN
    ALTER TABLE public.products ADD CONSTRAINT products_min_stock_nonnegative_chk CHECK (min_stock >= 0) NOT VALID;
  END IF;
END $$;

-- 2) Lengkapi catatan pembelian per item/faktur. Tabel dibuat jika belum ada.
CREATE TABLE IF NOT EXISTS public.stock_purchases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id uuid NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  client_id text NOT NULL,
  product_name text NOT NULL,
  barcode text,
  qty integer NOT NULL CHECK (qty > 0),
  unit_cost numeric NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
  total_cost numeric NOT NULL DEFAULT 0 CHECK (total_cost >= 0),
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(store_id, client_id)
);
ALTER TABLE public.stock_purchases ADD COLUMN IF NOT EXISTS invoice_no text;
ALTER TABLE public.stock_purchases ADD COLUMN IF NOT EXISTS supplier text;
ALTER TABLE public.stock_purchases ADD COLUMN IF NOT EXISTS notes text;
ALTER TABLE public.stock_purchases ADD COLUMN IF NOT EXISTS purchased_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE public.stock_purchases ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "store members read stock purchases" ON public.stock_purchases;
CREATE POLICY "store members read stock purchases" ON public.stock_purchases
  FOR SELECT TO authenticated USING (public.is_store_member(store_id));
DROP POLICY IF EXISTS "store managers insert stock purchases" ON public.stock_purchases;
CREATE POLICY "store managers insert stock purchases" ON public.stock_purchases
  FOR INSERT TO authenticated WITH CHECK (EXISTS (
    SELECT 1 FROM public.store_members sm WHERE sm.store_id=stock_purchases.store_id
      AND sm.user_id=auth.uid() AND sm.active=true AND sm.role IN ('owner','manager')
  ));
DROP POLICY IF EXISTS "store managers update stock purchases" ON public.stock_purchases;
CREATE POLICY "store managers update stock purchases" ON public.stock_purchases
  FOR UPDATE TO authenticated USING (EXISTS (
    SELECT 1 FROM public.store_members sm WHERE sm.store_id=stock_purchases.store_id
      AND sm.user_id=auth.uid() AND sm.active=true AND sm.role IN ('owner','manager')
  )) WITH CHECK (EXISTS (
    SELECT 1 FROM public.store_members sm WHERE sm.store_id=stock_purchases.store_id
      AND sm.user_id=auth.uid() AND sm.active=true AND sm.role IN ('owner','manager')
  ));
DROP POLICY IF EXISTS "store managers delete stock purchases" ON public.stock_purchases;
CREATE POLICY "store managers delete stock purchases" ON public.stock_purchases
  FOR DELETE TO authenticated USING (EXISTS (
    SELECT 1 FROM public.store_members sm WHERE sm.store_id=stock_purchases.store_id
      AND sm.user_id=auth.uid() AND sm.active=true AND sm.role IN ('owner','manager')
  ));

