-- 4) Audit permanen saat transaksi dihapus. Arsip berada di tabel terpisah.
CREATE TABLE IF NOT EXISTS public.sales_deletion_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id uuid NOT NULL,
  original_sale_id text NOT NULL,
  deleted_by uuid,
  deleted_at timestamptz NOT NULL DEFAULT now(),
  reason text NOT NULL DEFAULT 'Dihapus dari aplikasi; alasan tidak dikirim',
  sale_snapshot jsonb NOT NULL,
  UNIQUE(store_id, original_sale_id)
);
ALTER TABLE public.sales_deletion_audit ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "store managers read sales deletion audit" ON public.sales_deletion_audit;
CREATE POLICY "store managers read sales deletion audit" ON public.sales_deletion_audit
  FOR SELECT TO authenticated USING (EXISTS (
    SELECT 1 FROM public.store_members sm WHERE sm.store_id=sales_deletion_audit.store_id
      AND sm.user_id=auth.uid() AND sm.active=true AND sm.role IN ('owner','manager')
  ));

CREATE OR REPLACE FUNCTION public.kasir_idris_audit_sale_delete()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  INSERT INTO public.sales_deletion_audit
    (store_id, original_sale_id, deleted_by, reason, sale_snapshot)
  VALUES
    (OLD.store_id, OLD.id::text, auth.uid(),
     COALESCE(NULLIF(current_setting('app.sale_delete_reason', true), ''), 'Dihapus dari aplikasi; alasan tidak dikirim'),
     to_jsonb(OLD))
  ON CONFLICT (store_id, original_sale_id) DO NOTHING;
  RETURN OLD;
END;
$$;
DROP TRIGGER IF EXISTS kasir_idris_audit_sale_delete_trigger ON public.sales;
CREATE TRIGGER kasir_idris_audit_sale_delete_trigger
  BEFORE DELETE ON public.sales FOR EACH ROW
  EXECUTE FUNCTION public.kasir_idris_audit_sale_delete();

-- 5) Cegah client_tx_id yang sama tersimpan dua kali.
-- Jika ada data duplikat lama, index tidak dibuat dan SQL memberi peringatan; tidak menghapus duplikat otomatis.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='sales' AND column_name='client_tx_id'
  ) THEN
    IF EXISTS (
      SELECT 1 FROM public.sales WHERE client_tx_id IS NOT NULL
      GROUP BY store_id, client_tx_id HAVING count(*) > 1
    ) THEN
      RAISE NOTICE 'Index pencegah duplikat tidak dibuat: ada client_tx_id ganda di sales. Periksa duplikat dahulu; tidak ada data yang dihapus.';
    ELSE
      EXECUTE 'CREATE UNIQUE INDEX IF NOT EXISTS sales_store_client_tx_id_unique_idx ON public.sales (store_id, client_tx_id) WHERE client_tx_id IS NOT NULL';
    END IF;
  ELSE
    RAISE NOTICE 'Kolom sales.client_tx_id tidak ditemukan; pencegahan ganda perlu disesuaikan dengan skema aplikasi.';
  END IF;
END $$;

-- 6) Aktifkan Realtime untuk tabel terkait, bila publication tersedia.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['sales','sale_items','expenses','products','stock_purchases','store_finance_settings','sales_deletion_audit'] LOOP
    IF to_regclass('public.' || t) IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname='supabase_realtime' AND schemaname='public' AND tablename=t) THEN
      EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', t);
    END IF;
  END LOOP;
EXCEPTION WHEN undefined_object THEN
  RAISE NOTICE 'Publication supabase_realtime tidak ditemukan. Aktifkan Realtime dari Dashboard Supabase.';
END $$;

